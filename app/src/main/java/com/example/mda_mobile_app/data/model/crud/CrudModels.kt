package com.example.mda_mobile_app.data.model.crud

// GET/POST/PUT responses (JSON names intentionally match PHP API camelCase fields).
data class Badge(
    val badgeId: Int,
    val badgeName: String,
    val description: String,
    val iconName: String?,
    val pointsReward: Int,
    val requirementDescription: String,
    val createdAt: String
)

data class Medication(
    val medicationId: Int,
    val userId: Int,
    val medicationName: String,
    val notes: String?,
    val isActive: Boolean,
    val createdAt: String
)

data class Reminder(
    val reminderId: Int,
    val medicationId: Int,
    val reminderTime: String, // HH:MM:SS
    val repeatDaily: Boolean,
    val isEnabled: Boolean,
    val createdAt: String
)

data class MedicationLog(
    val logId: Int,
    val medicationId: Int,
    val reminderId: Int?,
    val scheduledAt: String, // YYYY-MM-DD HH:MM:SS
    val status: String,      // taken | skipped | missed
    val recordedAt: String,
    val notes: String?
)

data class UserBadge(
    val userId: Int,
    val badgeId: Int,
    val earnedAt: String
)

data class UserRewards(
    val userId: Int,
    val totalPoints: Int,
    val currentStreak: Int,
    val longestStreak: Int,
    val updatedAt: String
)

// Creation requests. IDs are generated by MySQL where the table uses AUTO_INCREMENT.
data class CreateBadgeRequest(
    val badgeName: String,
    val description: String,
    val requirementDescription: String,
    val iconName: String? = null,
    val pointsReward: Int = 0
)

data class CreateMedicationRequest(
    val userId: Int,
    val medicationName: String,
    val notes: String? = null,
    val isActive: Boolean = true
)

data class CreateReminderRequest(
    val medicationId: Int,
    val reminderTime: String,
    val repeatDaily: Boolean = true,
    val isEnabled: Boolean = true
)

data class CreateMedicationLogRequest(
    val medicationId: Int,
    val scheduledAt: String,
    val status: String,
    val reminderId: Int? = null,
    val notes: String? = null
)

data class CreateUserBadgeRequest(
    val userId: Int,
    val badgeId: Int,
    val earnedAt: String? = null
)

data class CreateUserRewardsRequest(
    val userId: Int,
    val totalPoints: Int = 0,
    val currentStreak: Int = 0,
    val longestStreak: Int = 0
)
